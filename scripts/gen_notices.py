#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.txt from what is actually linked/bundled.

Go modules come from `go list -deps` over the two binaries, so the list is what
the linker really pulls in rather than everything in go.mod. npm packages come
from `npm ls --omit=dev`, i.e. what can reach the browser bundle.
"""
import json, os, re, subprocess, sys, textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # the repo root
LICENSE_NAMES = ("LICENSE", "LICENSE.txt", "LICENSE.md", "LICENCE",
                 "COPYING", "LICENSE-MIT", "license", "License")


def find_license(d):
    for n in LICENSE_NAMES:
        p = os.path.join(d, n)
        if os.path.isfile(p):
            return p
    # some modules keep it one level down
    for sub in ("LICENSES", "licenses"):
        p = os.path.join(d, sub)
        if os.path.isdir(p):
            for f in sorted(os.listdir(p)):
                return os.path.join(p, f)
    return None


def classify(text):
    t = " ".join(text.split()).lower()
    if "apache license" in t and "version 2.0" in t:
        return "Apache-2.0"
    if "mozilla public license" in t:
        return "MPL-2.0"
    if "permission is hereby granted, free of charge" in t:
        return "MIT"
    if "redistribution and use in source and binary forms" in t:
        return "BSD-3-Clause" if "neither the name" in t else "BSD-2-Clause"
    if "permission to use, copy, modify, and/or distribute" in t:
        return "ISC"
    return "see text"


def go_modules():
    out = subprocess.run(
        ["go", "list", "-deps", "-tags", "webkit2_41", "-f",
         "{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}",
         "./ui", "./src/..."],
        cwd=ROOT, capture_output=True, text=True).stdout
    seen = {}
    for line in out.splitlines():
        if not line.strip() or line.startswith("my-backtester"):
            continue
        path, ver, d = line.split("|")
        seen[path] = (ver, d)
    return sorted(seen.items())


def npm_packages():
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json"],
                         cwd=os.path.join(ROOT, "ui/frontend"),
                         capture_output=True, text=True).stdout
    tree = json.loads(out)
    found = {}

    def walk(node):
        for name, info in (node.get("dependencies") or {}).items():
            if name.startswith("@types/"):
                continue          # type declarations, never in the bundle
            ver = info.get("version")
            if ver and name not in found:
                found[name] = ver
            walk(info)
    walk(tree)
    return sorted(found.items())


def npm_dir(name):
    return os.path.join(ROOT, "ui/frontend/node_modules", *name.split("/"))


def section(title, subtitle, license_path, declared=None):
    body = ""
    if license_path and os.path.isfile(license_path):
        body = open(license_path, encoding="utf-8", errors="replace").read().strip()
    spdx = declared or (classify(body) if body else "UNKNOWN")
    head = f"{'-' * 78}\n{title}\n{subtitle}\nLicense: {spdx}\n{'-' * 78}\n\n"
    return head + (body if body else
                   "!! No license file found in the distributed package. "
                   "Resolve before shipping.") + "\n\n"


def main():
    parts = []
    parts.append(textwrap.dedent("""\
        THIRD-PARTY NOTICES
        ===================

        Backtester is distributed as a single executable that statically links the
        Go libraries below, and as a web bundle that includes the JavaScript
        packages below. Their licences are permissive, and every one of them
        requires that its copyright and permission notice travel with the binary.
        That is what this file is.

        Nothing here is part of Backtester itself; see LICENSE for that, and
        DATA-LICENSE.md for the bundled market-data database.

        This file is generated by scripts/gen_notices.py. Regenerate it whenever a
        dependency is added, removed or upgraded -- a stale notices file is worse
        than none, because it asserts something untrue.

        """))

    go = go_modules()
    parts.append(f"\n{'=' * 78}\nGo modules ({len(go)})\n{'=' * 78}\n\n")
    for path, (ver, d) in go:
        parts.append(section(path, f"Version: {ver}", find_license(d)))
        # The DuckDB C++ library is statically linked. With duckdb-go v2 it
        # ships as its own module per platform
        # (github.com/duckdb/duckdb-go-bindings/lib/<os>-<arch>) carrying the
        # Stichting DuckDB Foundation's LICENSE, so the loop above already
        # emits its notice; the old go-duckdb special case is gone.

    npm = npm_packages()
    parts.append(f"\n{'=' * 78}\nnpm packages ({len(npm)})\n{'=' * 78}\n\n")
    for name, ver in npm:
        d = npm_dir(name)
        declared = None
        pj = os.path.join(d, "package.json")
        if os.path.isfile(pj):
            lic = json.load(open(pj)).get("license")
            if isinstance(lic, str) and (" OR " in lic or " AND " in lic):
                declared = lic
        parts.append(section(name, f"Version: {ver}", find_license(d), declared))

    out = "".join(parts)
    with open(os.path.join(ROOT, "THIRD-PARTY-NOTICES.txt"), "w") as f:
        f.write(out)
    print(f"wrote THIRD-PARTY-NOTICES.txt: {len(go)} Go modules, "
          f"{len(npm)} npm packages, {len(out)} bytes")


main()
